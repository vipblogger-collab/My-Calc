export function localizeCategory(cat: CategoryDef, lang: Language): CategoryDef {
  if (lang === 'en') return cat;
  const ar = CATEGORY_AR[cat.slug];
  if (!ar) return cat;
  return {
    ...cat,
    name: ar.name,
    shortName: ar.shortName,
    description: ar.description,
    disclaimer: ar.disclaimer ?? cat.disclaimer,
  };
}

export function localizeCalculator(calc: CalculatorDef, lang: Language): CalculatorDef {
  if (lang === 'en') return calc;
  const ar = CALCULATOR_AR[calc.slug];
  if (!ar) return calc;
  return {
    ...calc,
    name: ar.name,
    shortName: ar.shortName,
    description: ar.description,
    keywords: [...calc.keywords, ...ar.keywords],
    seoTitle: `${ar.name} – أداة حساب مجانية ودقيقة | smartcalc.net`,
    seoDescription: `${ar.description} نتائج فورية مع شرح المعادلة والأمثلة التطبيقية.`,
  };
}

export function localizeArticle(art: ArticleDef, lang: Language): ArticleDef {
  if (lang === 'en') return art;
  const ar = GUIDES_AR[art.slug];
  if (!ar) return art;
  return {
    ...art,
    title: ar.title,
    categoryLabel: ar.categoryLabel,
    readTime: ar.readTime,
    summary: ar.summary,
    sections: ar.sections,
  };
}
