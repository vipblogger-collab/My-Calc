export function translateWidgetLabel(text: string, lang: Language): string {
  if (lang === 'en') return text;
  if (WIDGET_AR_MAP[text]) return WIDGET_AR_MAP[text];
  if (OPTION_AR_MAP[text]) return OPTION_AR_MAP[text];

  // Pattern helpers for dynamic labels like "1 USD to EUR" or "Converted Time (Europe/London)"
  const curPairMatch = text.match(/^1 ([A-Z]{3}) to ([A-Z]{3})$/);
  if (curPairMatch) {
    return `1 ${curPairMatch[1]} إلى ${curPairMatch[2]}`;
  }
  const curEqMatch = text.match(/^(.+) ([A-Z]{3}) equals$/);
  if (curEqMatch) {
    return `${curEqMatch[1]} ${curEqMatch[2]} يساوي`;
  }
  const convTimeMatch = text.match(/^Converted Time \((.+)\)$/);
  if (convTimeMatch) {
    return `الوقت المحوّل (${convTimeMatch[1]})`;
  }
  if (text.endsWith(' equals')) {
    return `${text.slice(0, -7)} يساوي`;
  }

  return text;
}
